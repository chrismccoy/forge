/**
 * Removes comments and returns the remaining non-blank lines.
 *
 * Each comment is removed together with the spaces or tabs that follow it,
 * so a block comment placed before code on the same line leaves that code
 * line exactly as it was. Each line also records the gap before it: the
 * number of blank lines since the previous code line, or `*` when a comment
 * that starts its line sat in that gap or opens the line (blank lines may be
 * added or removed next to comments).
 *
 * @param {string}                              src    Source text.
 * @param {Array<{start: number, end: number}>} ranges Comment ranges, sorted.
 * @return {Array<{line: number, text: string, gap: number|string}>} Non-blank
 *         lines, right-trimmed, with their line in src and the gap before them.
 */
export function layoutLines( src, ranges ) {
	const raw = [];
	let text = '';
	let touched = false;
	let startLine = 1;
	let line = 1;
	let pos = 0;
	// Where a joined docstring was taken out of the current line (see below).
	let joins = [];
	const flush = () => {
		raw.push( { line: startLine, text: text.replace( /\s+$/, '' ), touched, joins } );
		text = '';
		touched = false;
		joins = [];
		line++;
		startLine = line;
	};
	const keep = ( from, to ) => {
		for ( let k = from; k < to; k++ ) {
			if ( src[ k ] === '\n' ) {
				flush();
			} else {
				text += src[ k ];
			}
		}
	};
	for ( const r of ranges ) {
		keep( pos, r.start );
		if ( r.join ) {
			// A docstring inside a form (Clojure) needs line breaks around it that the form
			// did not have: `(defn f [x]` becomes `(defn f` / `"Doc."` / `[x]`. Take it out
			// with the whitespace around it, rejoin the code on both sides into one line, and
			// record the join, so that verify can match either the joined line or its pieces.
			if ( text.trim() === '' && raw.length ) {
				const prev = raw.pop();
				text = prev.text;
				joins = prev.joins;
				touched = prev.touched;
				startLine = prev.line;
			}
			text = text.replace( /\s+$/, '' );
			let end = r.end;
			for ( let k = r.start; k < end; k++ ) {
				line += src[ k ] === '\n' ? 1 : 0;
			}
			while ( end < src.length && /\s/.test( src[ end ] ) ) {
				line += src[ end ] === '\n' ? 1 : 0;
				end++;
			}
			if ( text !== '' && end < src.length ) {
				const sep = /[)\]}]/.test( src[ end ] ) ? '' : ' ';
				joins = [ ...joins, { at: text.length, sep } ];
				text += sep;
			}
			pos = end;
			continue;
		}
		// Only a comment that starts its line (nothing but indentation before
		// it) loosens the blank-line rule; a trailing comment does not.
		touched = touched || text.trim() === '';
		// Lines inside a multi-line comment become comment lines of their own.
		for ( let k = r.start; k < r.end; k++ ) {
			if ( src[ k ] === '\n' ) {
				flush();
				touched = true;
			}
		}
		let end = r.end;
		while ( src[ end ] === ' ' || src[ end ] === '\t' ) {
			end++;
		}
		pos = end;
	}
	keep( pos, src.length );
	flush();

	const out = [];
	let blanks = 0;
	let commentInGap = false;
	for ( const l of raw ) {
		if ( l.text === '' ) {
			blanks++;
			commentInGap = commentInGap || l.touched;
			continue;
		}
		out.push( { line: l.line, text: l.text, gap: commentInGap || l.touched ? '*' : blanks, joins: l.joins } );
		blanks = 0;
		commentInGap = false;
	}
	return out;
}

/**
 * Tells whether two layout lines match: same text, and the same gap before
 * them unless a comment sits in either gap.
 *
 * @param {Object} a Layout line from layoutLines().
 * @param {Object} b Layout line from layoutLines().
 * @return {boolean} True when they match.
 */
export function sameLayout( a, b ) {
	return a.text === b.text && ( a.gap === '*' || b.gap === '*' || a.gap === b.gap );
}

/**
 * Tells how many lines of `ys`, from index `k`, line `x` stands for when it is
 * split at some of its docstring joins (see layoutLines). The joined line itself
 * is compared by sameLayout.
 *
 * @param {Object}   x  Layout line, maybe with joins.
 * @param {Object[]} ys Layout lines of the other side.
 * @param {number}   k  Index in ys to match from.
 * @return {number} Lines of ys matched, or 0.
 */
function splitMatch( x, ys, k ) {
	const joins = ( x?.joins || [] ).slice( 0, 8 );
	for ( let mask = 1; mask < 1 << joins.length; mask++ ) {
		const pieces = [];
		let from = 0;
		joins.forEach( ( j, n ) => {
			if ( mask & ( 1 << n ) ) {
				pieces.push( x.text.slice( from, j.at ) );
				from = j.at + j.sep.length;
			}
		} );
		pieces.push( x.text.slice( from ) );
		if ( pieces.every( ( p, n ) => ys[ k + n ] && ys[ k + n ].text.trim() === p.trim() ) ) {
			return pieces.length;
		}
	}
	return 0;
}

/**
 * Compares two layouts and returns the index in `lb` of the first line that
 * does not match, or -1. A line joined around a docstring matches the same
 * code split over several lines on the other side.
 *
 * @param {Object[]} la Layout of the original.
 * @param {Object[]} lb Layout of the edited file.
 * @return {number} Index of the first mismatch in lb, or -1.
 */
export function layoutMismatch( la, lb ) {
	let i = 0;
	let j = 0;
	while ( i < la.length || j < lb.length ) {
		if ( la[ i ] && lb[ j ] && sameLayout( la[ i ], lb[ j ] ) ) {
			i++;
			j++;
			continue;
		}
		const ma = splitMatch( lb[ j ], la, i );
		if ( ma ) {
			i += ma;
			j++;
			continue;
		}
		const mb = splitMatch( la[ i ], lb, j );
		if ( mb ) {
			i++;
			j += mb;
			continue;
		}
		return Math.min( j, lb.length - 1 );
	}
	return -1;
}

/**
 * Builds the comparison model for one script.
 *
 * @param {string} src      Script source.
 * @param {string} lang     js, ts, tsx or dts.
 * @param {Object} opts     Options for classify().
 * @param {number} [prefer] Plugin set to try first.
 * @return {Object} {ast, cfg, words, code, layout, comments} or {error}.
 */
function scriptModel( src, lang, opts, prefer ) {
	let parsed;
	try {
		parsed = jsParse( src, lang, prefer );
	} catch ( e ) {
		return { error: 'parse error: ' + e.message };
	}
	const { ast, cfg } = parsed;
	const comments = [];
	const words = [];
	let anchor = 0;
	for ( const t of ast.tokens ) {
		const label = typeof t.type === 'string' ? t.type : t.type.label;
		if ( label === 'CommentBlock' || label === 'CommentLine' ) {
			const text = src.slice( t.start, t.end );
			comments.push( { text, line: t.loc.start.line, anchor, ...classify( text, opts ) } );
		} else if ( label !== 'eof' ) {
			words.push( src.slice( t.start, t.end ) );
			anchor++;
		}
	}
	return {
		ast,
		cfg,
		words,
		code: jsCanonical( ast ),
		layout: layoutLines( src, ast.comments.map( ( c ) => ( { start: c.start, end: c.end } ) ) ),
		comments,
	};
}

/**
 * Builds the comparison model for one file.
 *
 * For a component, `code` joins the markup and every script's canonical AST,
 * comment anchors are prefixed with the block index (`1:42`), and layout
 * lines carry the block index and file line numbers.
 *
 * @param {string}   file     Path (for the extension).
 * @param {string}   src      Source text.
 * @param {Object}   [opts]   Options for classify().
 * @param {number[]} [prefer] Plugin set per script, from the original's model.
 * @return {Promise<Object>} {lang, markup?, code, layout, comments, cfgs, scripts} or {error}.
 */
export async function model( file, src, opts = {}, prefer = [] ) {
	const tsLang = ! JS_EXT.has( extname( file ) ) && ! SFC_EXT.has( extname( file ) ) && langFor( file );
	if ( tsLang ) {
		const { tsModel } = await import( './treesitter.mjs' );
		try {
			return await tsModel( tsLang, src, { checkedTypes: opts.checkedTypes } );
		} catch ( e ) {
			return { error: `parse error: ${ e.message }` };
		}
	}
	if ( ! SFC_EXT.has( extname( file ) ) ) {
		const lang = langOf( file );
		// prefer is ['ts'] when the original needed the tree-sitter fallback.
		const m = prefer[ 0 ] === 'ts' ? { error: 'fallback' } : scriptModel( src, lang, opts, prefer[ 0 ] );
		if ( m.error ) {
			// Only an original Babel cannot parse (or a file whose original needed it)
			// falls back; a current file that stopped parsing is a code change.
			if ( prefer.length && prefer[ 0 ] !== 'ts' ) {
				return m;
			}
			const { tsModel } = await import( './treesitter.mjs' );
			const tsLang = { js: 'javascript', tsx: 'tsx' }[ lang ] || 'typescript';
			try {
				const t = await tsModel( tsLang, src, { classify: ( text ) => classify( text, opts ) } );
				return { ...t, cfgs: [ 'ts' ], fallback: m.error };
			} catch ( e ) {
				return m;
			}
		}
		return { lang: 'js', code: m.code, layout: m.layout, comments: m.comments, cfgs: [ m.cfg ], scripts: [ m ] };
	}
	const { markup, blocks } = splitSfc( src, file );
	const scripts = [];
	const layout = [];
	const comments = [];
	for ( const [ i, b ] of blocks.entries() ) {
		const m = scriptModel( b.content, b.lang, opts, prefer[ i ] );
		if ( m.error ) {
			return { error: `<script> block ${ i + 1 }: ${ m.error }` };
		}
		m.block = b;
		scripts.push( m );
		m.layout.forEach( ( l ) => layout.push( { ...l, line: l.line + b.line - 1, text: i + '|' + l.text } ) );
		m.comments.forEach( ( c ) => comments.push( { ...c, line: c.line + b.line - 1, anchor: i + ':' + c.anchor } ) );
	}
	return {
		lang: 'sfc',
		markup,
		code: markup + '\u0001' + scripts.map( ( s ) => s.code ).join( '\u0001' ),
		layout,
		comments,
		cfgs: scripts.map( ( s ) => s.cfg ),
		scripts,
	};
}
