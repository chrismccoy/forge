/**
 * Splits a Vue or Svelte component into top-level script blocks and markup.
 *
 * Only a <script> tag that starts a line counts as a top-level block; a
 * script inside markup (for example in <svelte:head>) is page output and
 * stays part of the markup.
 *
 * Astro components (`file` ending `.astro`) also have a frontmatter block
 * between `---` fences at the top, which is TypeScript. Their `<script>`
 * tags may be indented and are TypeScript; a script with any attribute other
 * than `src` (`is:inline`, `type="module"`, `define:vars`) is sent to the
 * page as written, so it stays markup. A
 * self-closing `<script … />` and a script whose `type` is not JavaScript
 * (`application/ld+json`, `text/partytown` …) stay part of the markup, in
 * every component kind.
 *
 * @param {string} src  Component source.
 * @param {string} file File name, to tell Astro from Vue and Svelte.
 * @return {{markup: string, blocks: Array<{lang: string, content: string, line: number, start: number, frontmatter: boolean}>}}
 *         Markup with each script body replaced by a placeholder, and the
 *         script bodies with their language, first line and offset in src.
 */
export function splitSfc( src, file = '' ) {
	const astro = file.endsWith( '.astro' );
	// Attribute values may contain `>` (Vue `generic="T extends Record<string, unknown>"`).
	const re = astro
		? /^[ \t]*<script\b((?:[^>"']|"[^"]*"|'[^']*')*)>([\s\S]*?)<\/script\s*>/gim
		: /^<script\b((?:[^>"']|"[^"]*"|'[^']*')*)>([\s\S]*?)<\/script\s*>/gim;
	const blocks = [];
	let markup = '';
	let pos = 0;
	const add = ( bodyStart, content, lang, frontmatter = false ) => {
		markup += src.slice( pos, bodyStart ) + '\u0000SCRIPT\u0000';
		blocks.push( { lang, content, line: src.slice( 0, bodyStart ).split( '\n' ).length, start: bodyStart, frontmatter } );
		pos = bodyStart + content.length;
	};
	if ( astro ) {
		const fm = /^(﻿?---[ \t]*\r?\n)([\s\S]*?)(?:^|\n)---[ \t]*(?:\r?\n|$)/.exec( src );
		if ( fm ) {
			// The body ends before the line break that precedes the closing fence.
			const body = fm[ 2 ].endsWith( '\r' ) ? fm[ 2 ].slice( 0, -1 ) : fm[ 2 ];
			add( fm[ 1 ].length, body, 'ts', true );
			re.lastIndex = pos;
		}
	}
	let m;
	while ( ( m = re.exec( src ) ) ) {
		const attrs = m[ 1 ];
		const type = ( /\btype\s*=\s*["']?([^"'\s>]+)/i.exec( attrs ) || [] )[ 1 ];
		// A self-closing tag has no body: the lazy match would run on to the next `</script>`.
		if ( /\/\s*$/.test( attrs ) ) {
			re.lastIndex = m.index + m[ 0 ].indexOf( '>' ) + 1;
			continue;
		}
		if ( type && ! /^(module|text\/javascript|application\/javascript|text\/typescript)$/i.test( type ) ) {
			continue;
		}
		// Astro ships a script with any attribute other than `src` (`is:inline`,
		// `type="module"`, `define:vars`) verbatim into the page: it is markup.
		if ( astro && attrs.replace( /\bsrc\s*=\s*("[^"]*"|'[^']*'|\S+)/, '' ).trim() ) {
			continue;
		}
		const bodyStart = m.index + m[ 0 ].indexOf( '<script' ) + '<script'.length + attrs.length + 1;
		let lang = ( /\blang\s*=\s*["']?(ts|tsx|typescript|js|jsx)\b/i.exec( attrs ) || [] )[ 1 ] || ( astro ? 'ts' : 'js' );
		lang = lang === 'typescript' ? 'ts' : lang.toLowerCase();
		add( bodyStart, m[ 2 ], lang );
	}
	markup += src.slice( pos );
	return { markup, blocks };
}

