/**
 * Shared parsing and comment classification for the doc-pass checker.
 *
 * JS / TS is parsed with @babel/parser. Vue, Svelte and Astro components are
 * split into their script blocks (Astro: also the frontmatter), which are
 * parsed the same way, and the markup around them, which is compared byte for
 * byte. Every other language (langs.mjs) is parsed with tree-sitter
 * (treesitter.mjs) or a reader of the checker's own.
 */

import { closeSync, lstatSync, openSync, readFileSync, readSync, readdirSync } from 'node:fs';
import { basename, extname, join, relative } from 'node:path';
import { parse as babelParse } from '@babel/parser';
import { langFor } from './langs.mjs';

export const JS_EXT = new Set( [ '.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.mts', '.cts' ] );
export const SFC_EXT = new Set( [ '.vue', '.svelte', '.astro' ] );
const SKIP_DIRS = new Set( [
	'node_modules', 'bower_components', 'jspm_packages', 'vendor', 'build', 'dist', 'out', 'coverage',
	'storybook-static', '__generated__', 'target', '__pycache__', 'venv', 'site-packages', 'obj',
	'Pods', 'DerivedData',
] );
// Pruned folders whose names a real source package can also have
// (`internal/build/`, `mypkg/out/`): reported when they hold source files.
const AMBIGUOUS_DIRS = new Set( [ 'vendor', 'build', 'dist', 'out', 'coverage', 'target', 'obj', '__generated__' ] );
const SKIP_FILE = /^Kconfig\b|^_ide_helper\w*\.php$|^\.phpstorm\.meta\.php$|\.(min|bundle|generated|gen)\.[cm]?[jt]sx?$|\.timestamp-\d+[-\w]*\.mjs$|^(next-env|auto-imports|components|typed-router|worker-configuration)\.d\.ts$/;

/**
 * Tells whether a path is an in-scope source file by its name.
 *
 * @param {string} name File name or path.
 * @return {boolean} True for source files (JS / TS / SFC, or a tree-sitter language) that are
 *                   not minified or generated by name.
 */
export function isSource( name ) {
	const ext = extname( name );
	return ( JS_EXT.has( ext ) || SFC_EXT.has( ext ) || !! langFor( name ) ) && ! SKIP_FILE.test( basename( name ) );
}

/**
 * Tells whether a path is a test file, whose test callbacks need no JSDoc.
 *
 * @param {string} file Relative path.
 * @return {boolean} True for *.test.*, *.spec.*, __tests__/, __mocks__/, test(s)/ and e2e/ files.
 */
export function isTestFile( file ) {
	return /(^|\/)(__tests__|__mocks__|tests?|e2e|cypress|playwright)\//.test( file ) ||
		/\.(test|spec|e2e|cy)\.[cm]?[jt]sx?$/.test( file );
}

// Generated-file markers, judged per line so prose that mentions
// "auto-generated" or a string holding "Do not edit" does not hide a real
// source file. Only the first 20 lines count. A marker either starts a line (after any comment marker), or
// sits anywhere in a comment line: `DO NOT EDIT`, `@generated`, "this file
// was generated", "do not edit by hand".
const COMMENT_START = String.raw`^[ \t]*(?:\/\/+|#+|\/\*+|\*+|--+|;+|%+|<!--)`;
const GENERATED_AT_START = new RegExp( COMMENT_START + String.raw`?[ \t]*(?:@generated\b|Code generated\b|Generated (?:file|code)\b|DO NOT EDIT\b|DO NOT MODIFY BY HAND|GENERATED CODE\b|<auto-generated|auto(?:-|matically )?generated\b|This (?:file|code|class) (?:is|was|has been) (?:auto(?:-| |matically )?)?generated\b|This is (?:an )?auto(?:-|matically )?generated\b|Generated by Django\b|Generated for Laravel\b)`, 'mi' );
const GENERATED_IN_COMMENT = new RegExp( COMMENT_START + String.raw`.*(?:\bDO NOT EDIT\b|@generated\b)`, 'm' );
const GENERATED_PHRASE = new RegExp( COMMENT_START + String.raw`.*(?:\b(?:this|the) (?:file|code) (?:is|was|has been) (?:auto(?:-| |matically )?)?generated\b|\bdo not (?:edit|modify)(?: this file)? (?:by hand|manually|directly)\b|\bdo not (?:edit|modify)\b[.!]?[ \t]*(?:\*\/)?[ \t]*$)`, 'mi' );

/**
 * Tells whether a file is binary or marked generated (a comment line that
 * starts with `@generated`, `DO NOT EDIT`, `auto-generated` …), judging by
 * its first 20 lines within the first 2 KB.
 *
 * @param {string} path File path.
 * @return {boolean} True when the marker is present.
 */
export function isGenerated( path ) {
	const fd = openSync( path, 'r' );
	const buf = Buffer.alloc( 2048 );
	const n = readSync( fd, buf, 0, 2048, 0 );
	closeSync( fd );
	// A NUL byte means binary data with a source extension (`.ts` MPEG
	// transport-stream video fixtures, for example).
	// Markers sit at the top of a file; later lines are prose about the code.
	const text = buf.toString( 'utf8', 0, n ).replace( /^\uFEFF/, '' ).split( '\n' ).slice( 0, 20 ).join( '\n' );
	return buf.subarray( 0, n ).includes( 0 ) || [ GENERATED_AT_START, GENERATED_IN_COMMENT, GENERATED_PHRASE ].some( ( re ) => re.test( text ) );
}

/**
 * Reads a newline-separated path list (blank lines and `#` comments ignored).
 *
 * @param {string} path List file.
 * @return {string[]} Paths.
 */
export function readList( path ) {
	try {
		return readFileSync( path, 'utf8' ).split( '\n' ).map( ( l ) => l.trim() ).filter( ( l ) => l && ! l.startsWith( '#' ) );
	} catch {
		console.error( `Cannot read file list: ${ path }` );
		process.exit( 2 );
	}
}

/**
 * Splits checker arguments into flags, positional arguments and files.
 *
 * Flags may come in any order. `--files-from <list>` adds the paths in a
 * list file after the positional arguments and the files given on the
 * command line. A flag in `valued` takes the next argument as its value; a
 * missing value exits with status 2.
 *
 * @param {string[]} argv   Arguments after the script name.
 * @param {string[]} flags  Boolean flags the script accepts.
 * @param {string[]} valued Flags that take a value.
 * @return {{flags: Object<string, boolean>, values: Object<string, string>, rest: string[], listed: boolean}}
 *         Flags set, flag values, the other arguments in order, and whether a `--files-from` list was given
 *         (an empty list means no files, not the whole tree).
 */
export function parseArgs( argv, flags, valued = [] ) {
	const set = {};
	const values = {};
	const rest = [];
	const fromLists = [];
	let listed = false;
	for ( let i = 0; i < argv.length; i++ ) {
		const a = argv[ i ];
		if ( a === '--files-from' || valued.includes( a ) ) {
			const v = argv[ ++i ];
			if ( v === undefined || v.startsWith( '--' ) ) {
				console.error( `${ a } needs a value` );
				process.exit( 2 );
			}
			if ( a === '--files-from' ) {
				listed = true;
				fromLists.push( ...readList( v ) );
			} else {
				values[ a.replace( /^--/, '' ) ] = v;
			}
		} else if ( flags.includes( a ) ) {
			set[ a.replace( /^--/, '' ) ] = true;
		} else {
			rest.push( a );
		}
	}
	return { flags: set, values, rest: [ ...rest, ...fromLists ], listed };
}

/**
 * Tells whether a folder holds a source file, looking at no more than about
 * 2,000 entries so a large build tree stays cheap.
 *
 * @param {string} dir Folder.
 * @return {boolean} True when a source file was found.
 */
function holdsSource( dir ) {
	const queue = [ dir ];
	let seen = 0;
	while ( queue.length && seen < 2000 ) {
		const at = queue.shift();
		let names;
		try {
			names = readdirSync( at, { withFileTypes: true } );
		} catch {
			continue;
		}
		for ( const d of names ) {
			seen++;
			if ( d.isDirectory() && ! d.name.startsWith( '.' ) && d.name !== 'node_modules' ) {
				queue.push( join( at, d.name ) );
			} else if ( d.isFile() && isSource( d.name ) && ! /\.(min|map)\./.test( d.name ) ) {
				return true;
			}
		}
	}
	return false;
}

/**
 * Lists in-scope source files under a directory, as paths relative to it.
 *
 * Skips dependency, vendored, build and cache folders, every dot folder
 * (.git, .next, .nuxt, .svelte-kit, .output, .turbo …) and symlinks.
 *
 * @param {string}        root        Directory to walk.
 * @param {string[]|null} skipped     Receives source files left out as binary or generated, when given.
 * @param {string[]|null} skippedDirs Receives the pruned folders named like build output (`build/`,
 *                                    `out/`, `target/`, `vendor/` …) that hold source files, when given.
 * @return {string[]} Relative paths, sorted.
 */
export function walk( root, skipped = null, skippedDirs = null ) {
	const out = [];
	const visit = ( dir ) => {
		for ( const name of readdirSync( dir ) ) {
			const full = join( dir, name );
			const st = lstatSync( full );
			// Symlinks are never followed: they can dangle (into a missing
			// node_modules) or lead outside the project.
			if ( st.isSymbolicLink() ) {
				continue;
			}
			if ( st.isDirectory() ) {
				// CLion names its build folders `cmake-build-<profile>`.
				if ( ! SKIP_DIRS.has( name ) && ! name.startsWith( '.' ) && ! name.startsWith( 'cmake-build-' ) ) {
					visit( full );
				} else if ( skippedDirs && AMBIGUOUS_DIRS.has( name ) && holdsSource( full ) ) {
					skippedDirs.push( relative( root, full ) );
				}
				continue;
			}
			// Framework caches of compiled PHP (Laravel bootstrap/cache, storage/framework).
			if ( isSource( relative( root, full ) ) && ! /(^|\/)(bootstrap\/cache|storage\/framework)\//.test( relative( root, full ) ) ) {
				if ( ! isGenerated( full ) ) {
					out.push( relative( root, full ) );
				} else if ( skipped ) {
					skipped.push( relative( root, full ) );
				}
			}
		}
	};
	visit( root );
	return out.sort();
}

/**
 * Lists the Babel plugin sets to try for a file, most likely first.
 *
 * TypeScript files try legacy decorators first (NestJS, TypeORM, Angular,
 * parameter decorators), then standard decorators (`export @dec class`).
 * Declaration files (.d.ts) parse in ambient mode.
 *
 * @param {string} lang Script language: js, jsx, ts, tsx or dts.
 * @param {string} src  Source text, checked for a @flow pragma.
 * @return {Array<Array>} Plugin lists.
 */
function pluginSets( lang, src ) {
	const extra = [ 'explicitResourceManagement' ];
	if ( lang === 'dts' ) {
		return [ [ [ 'typescript', { dts: true } ] ] ];
	}
	if ( lang === 'ts' || lang === 'tsx' ) {
		const base = lang === 'tsx' ? [ 'typescript', 'jsx' ] : [ 'typescript' ];
		return [ [ ...base, 'decorators-legacy', ...extra ], [ ...base, 'decorators', ...extra ] ];
	}
	const flow = /@flow\b/.test( src.slice( 0, 4000 ) ) ? [ 'flow' ] : [];
	return [
		[ 'jsx', ...flow, 'decorators-legacy', ...extra ],
		[ 'jsx', ...flow, 'decorators', ...extra ],
		[ ...flow, 'decorators-legacy', ...extra ],
	];
}

/**
 * Picks the script language from a file name.
 *
 * @param {string} file Path.
 * @return {string} js, ts, tsx or dts.
 */
export function langOf( file ) {
	if ( /\.d\.[cm]?ts$/.test( file ) ) {
		return 'dts';
	}
	const ext = extname( file );
	if ( ext === '.tsx' ) {
		return 'tsx';
	}
	return [ '.ts', '.mts', '.cts' ].includes( ext ) ? 'ts' : 'js';
}

/**
 * Parses JS / TS source with Babel.
 *
 * Tries each plugin set in turn. Pass the `cfg` the original file parsed
 * with as `prefer`, so both versions of a file are parsed the same way.
 *
 * @param {string} src      Source text.
 * @param {string} lang     js, ts, tsx or dts.
 * @param {number} [prefer] Index of the plugin set to try first.
 * @return {{ast: Object, cfg: number}} Babel File node (with tokens) and the plugin set used.
 */
export function jsParse( src, lang, prefer ) {
	const sets = pluginSets( lang, src );
	const order = sets.map( ( _, i ) => i );
	if ( prefer !== undefined && order.includes( prefer ) ) {
		order.splice( order.indexOf( prefer ), 1 );
		order.unshift( prefer );
	}
	let first;
	for ( const i of order ) {
		try {
			const ast = babelParse( src, {
				sourceType: 'unambiguous',
				plugins: sets[ i ],
				tokens: true,
				errorRecovery: false,
				allowReturnOutsideFunction: true,
				allowAwaitOutsideFunction: true,
				allowUndeclaredExports: true,
			} );
			return { ast, cfg: i };
		} catch ( e ) {
			first = first || e;
		}
	}
	throw first;
}

const AST_DROP = new Set( [
	'start', 'end', 'loc', 'range', 'comments', 'leadingComments', 'trailingComments',
	'innerComments', 'extra', 'tokens', 'errors',
] );

/**
 * Serializes a Babel AST with positions and comments removed.
 *
 * `extra` holds raw literal text, so quote style is not compared here; the
 * layout check catches that.
 *
 * @param {Object} ast Babel File node.
 * @return {string} Canonical JSON.
 */
export function jsCanonical( ast ) {
	return JSON.stringify( ast, ( k, v ) => ( AST_DROP.has( k ) ? undefined : v ) );
}

