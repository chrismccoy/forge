// Frozen whole when any line of the comment starts with one of these: JSX
// pragmas, spec-generating API blocks, generated-file markers, license text.
const FROZEN_WHOLE_LINE = /^(@jsx(Runtime|ImportSource|Frag)?\b|@(flow|noflow)\b|@(openapi|swagger)\b|@api(\s*\{|[A-Z]\w*)|@generated\b|@preserve\b|@license\b|Copyright\b|\(c\)\s*\d|©|SPDX-License-Identifier|.*\bGNU (Lesser |Affero )?General Public License|Permission is hereby granted|Licensed under the)/;

// Single lines frozen wherever they appear: test-runner and formatter
// pragmas, and tags that change emitted declarations, type checking or
// generated docs (stripInternal, checked-JS modifiers, API Extractor release
// tags, TypeDoc visibility, deprecation). Never added, removed or edited.
const FROZEN_LINE = [
	/^@(jest-environment|jest-environment-options|vitest-environment|vitest-environment-options|format|prettier|noformat)\b/,
	/^@(deprecated|internal|hidden|ignore|public|alpha|beta|experimental|private|protected|readonly|override|sealed|virtual)\b/,
];

// With --schema-tags (tsoa, typescript-json-schema, ts-json-schema-generator
// or typia present): JSDoc tags that those tools turn into validation rules or
// spec fields. Never add, remove or edit them.
const SCHEMA_LINE = /^@(isInt|isFloat|isLong|isDouble|isDate|isDateTime|isString|isBoolean|isArray|minimum|maximum|exclusiveMinimum|exclusiveMaximum|multipleOf|minLength|maxLength|pattern|format|minItems|maxItems|uniqueItems|minProperties|maxProperties|default|examples?|asType|nullable|discriminator|title|readOnly|writeOnly|contentMediaType|contentEncoding|TJS-\w+|type\s+(int32|int64|uint32|uint64|float|double))\b/;

// Lines that must survive but may gain siblings. Tags that carry a type keep
// only their tag, type and name: the description may change. With
// --checked-js, @param / @returns lines that carry a braced type are kept too.
const KEPT_WHOLE = /^@(since|see|link|author|packageDocumentation|module)\b/;
const KEPT_TYPED = /^@(typedef|callback|type|satisfies|template|this|enum|augments|extends|implements|import|overload|property|prop)\b/;
const KEPT_PARAM = /^@(param|arg|argument|returns?)\s*\{/;

/**
 * Splits a comment into trimmed content lines with comment markers removed.
 *
 * @param {string}  text      Raw comment text.
 * @param {boolean} keepBlank Keep empty lines (they end a joined tag line).
 * @return {string[]} Lines, internal whitespace collapsed; non-empty only unless keepBlank.
 */
function commentLines( text, keepBlank = false ) {
	const lines = text
		.replace( /^\/\*\*?|\*\/$/g, '' )
		.split( '\n' )
		.map( ( l ) => l.replace( /^\s*(\*|\/\/)?\s*/, '' ).replace( /\s+/g, ' ' ).trim() );
	return keepBlank ? lines : lines.filter( Boolean );
}

/**
 * Joins a tag line that opens more brackets than it closes with the lines
 * that follow, until they balance, so an annotation or type that spans lines
 * (`@ORM\Column(` … `)`, `@typedef {{` … `}} Row`) is classified as one line.
 * A blank line or a new lower-case tag (`@param`) ends the run early.
 *
 * @param {string[]} lines Trimmed comment lines.
 * @return {string[]} The lines, with each multi-line tag joined by spaces.
 */
export function joinTagLines( lines ) {
	const out = [];
	for ( let i = 0; i < lines.length; i++ ) {
		let l = lines[ i ];
		if ( /^[@\\]/.test( l ) ) {
			let depth = bracketDepth( l );
			while ( depth > 0 && i + 1 < lines.length && lines[ i + 1 ] && ! /^@[a-z]/.test( lines[ i + 1 ] ) ) {
				l += ' ' + lines[ ++i ];
				depth += bracketDepth( lines[ i ] );
			}
		}
		out.push( l );
	}
	return out;
}

/**
 * Counts the `(`, `{` and `[` a line leaves open, minus the ones it closes.
 *
 * @param {string} l Line.
 * @return {number} Net open brackets.
 */
function bracketDepth( l ) {
	let d = 0;
	for ( const ch of l ) {
		d += '({['.includes( ch ) ? 1 : ')}]'.includes( ch ) ? -1 : 0;
	}
	return d;
}

/**
 * Reduces a typed tag line to its tag, braced type and name.
 *
 * @param {string} line Trimmed comment line starting with a typed tag.
 * @return {string} The part of the line that must survive.
 */
function typedKey( line ) {
	const tag = /^@\w+/.exec( line )[ 0 ];
	let i = tag.length;
	while ( line[ i ] === ' ' ) {
		i++;
	}
	if ( line[ i ] === '{' ) {
		let depth = 0;
		for ( ; i < line.length; i++ ) {
			depth += line[ i ] === '{' ? 1 : line[ i ] === '}' ? -1 : 0;
			if ( depth === 0 ) {
				i++;
				break;
			}
		}
	}
	const rest = line.slice( i ).trim();
	const name = /^(\[[^\]]*\]|[^\s]+)/.exec( rest );
	return ( line.slice( 0, i ) + ( name && ! /^[-–]/.test( name[ 0 ] ) ? ' ' + name[ 0 ] : '' ) ).trim();
}

/**
 * Classifies one comment.
 *
 * @param {string}  text               Raw comment text.
 * @param {Object}  [opts]             Options.
 * @param {boolean} [opts.schemaTags] Freeze validation / schema JSDoc tags.
 * @param {boolean} [opts.checkedJs]  Keep the types on @param / @returns lines.
 * @return {{whole: boolean, frozen: string[], kept: string[]}} Classification.
 */
export function classify( text, opts = {} ) {
	const lines = joinTagLines( commentLines( text, true ) ).filter( Boolean );
	const whole = FROZEN_WHOLE.some( ( re ) => re.test( text ) ) || lines.some( ( l ) => FROZEN_WHOLE_LINE.test( l ) );
	const frozen = [];
	const kept = [];
	if ( ! whole ) {
		for ( const l of lines ) {
			if ( FROZEN_LINE.some( ( re ) => re.test( l ) ) || ( opts.schemaTags && SCHEMA_LINE.test( l ) ) ) {
				frozen.push( l );
			} else if ( KEPT_WHOLE.test( l ) ) {
				kept.push( l );
			} else if ( KEPT_TYPED.test( l ) || ( opts.checkedJs && KEPT_PARAM.test( l ) ) ) {
				kept.push( typedKey( l ) );
			}
		}
	}
	return { whole, frozen, kept };
}

