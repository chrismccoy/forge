def route_params(path: Path):
    """
    Return [(name, ts_key, ts_type)] for every dynamic segment in path, in order.

    [id] -> id: string, [...slug] -> slug: string[], [[...slug]] -> slug?: string[].
    """
    params = []
    for part in path.parts:
        m = re.fullmatch(r'\[(\[)?(\.\.\.)?(\w+)\]?\]', part)
        if m:
            key = f'{m.group(3)}?' if m.group(1) else m.group(3)
            params.append((m.group(3), key, 'string[]' if m.group(2) else 'string'))
    return params


def generate_route(args):
    """Generate a Route Handler (authenticated by default)."""
    path = resolve_app_path(Path(args.path))
    methods = [m.strip().upper() for m in args.methods.split(',') if m.strip()]
    with_auth = not args.no_auth

    # [id] as the last segment -> item route (GET/PUT/PATCH/DELETE one row);
    # otherwise a collection route (GET list / POST create).
    params = route_params(path)
    is_item = bool(params) and re.fullmatch(r'\[.*\]', path.name) is not None
    kind = 'item' if is_item else 'collection'
    unsupported = [m for m in methods if m not in ROUTE_METHODS[kind]]
    if unsupported:
        hint = ("use a collection path (e.g. app/api/posts) for POST"
                if is_item else
                "use an item path (e.g. app/api/posts/[id]) for PUT/PATCH/DELETE")
        print(f"Error: {', '.join(unsupported)} not supported on a {kind} route "
              f"({path}); supported: {', '.join(ROUTE_METHODS[kind])}. {hint}.",
              file=sys.stderr)
        sys.exit(1)

    # Next.js 15+/16: route handler params are a Promise in the 2nd argument
    if params:
        params_type = '{ ' + '; '.join(f'{key}: {t}' for _, key, t in params) + ' }'
        sig = f'(\n  request: Request,\n  context: {{ params: Promise<{params_type}> }}\n)'
        names = [n for n, _, _ in params]
        params_line = f"    const {{ {', '.join(names)} }} = await context.params;\n"
        parents = names[:-1] if is_item else names
        if parents and with_auth:
            params_line += (f"    // Also verify the caller may access the parent "
                            f"resource(s): {', '.join(parents)}\n")
    else:
        sig = '(request: Request)'
        params_line = ''
    item_id = params[-1][0] if is_item else None
    id_field = 'id' if item_id == 'id' else f'id: {item_id}'  # TS shorthand

    if with_auth:
        auth_check = (
            "    // Authorize inside the handler: proxy.ts/middleware.ts alone is not authorization\n"
            "    const session = await auth();\n"
            "    if (!session?.user?.id) {\n"
            "      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });\n"
            "    }\n\n"
        )
        owner_filter = '    //   where: { ownerId: session.user.id },\n'
        owner_data = ', ownerId: session.user.id'
        where = f'{id_field}, ownerId: session.user.id' if is_item else ''
        lookup = (
            "\n"
            "    // Ownership check - fails closed (404) until wired to your data layer.\n"
            f"    // const item = await db.items.findUnique({{ where: {{ {id_field} }} }});\n"
            "    const item = null as { ownerId: string } | null; // TODO: replace with the lookup above\n"
            "    if (!item || item.ownerId !== session.user.id) {\n"
            "      // 404 rather than 403 so callers cannot probe which ids exist\n"
            "      return NextResponse.json({ error: 'Not found' }, { status: 404 });\n"
            "    }\n"
        ) if is_item else ''
    else:
        auth_check = '    // NO AUTH CHECK (generated with --no-auth) - anyone can call this\n\n'
        owner_filter = ''
        owner_data = ''
        where = id_field if is_item else ''
        lookup = (
            "\n"
            "    // NO OWNERSHIP CHECK (generated with --no-auth)\n"
            f"    // const item = await db.items.findUnique({{ where: {{ {id_field} }} }});\n"
            "    const item = null as unknown; // TODO: replace with the lookup above\n"
            "    if (!item) {\n"
            "      return NextResponse.json({ error: 'Not found' }, { status: 404 });\n"
            "    }\n"
        ) if is_item else ''

    needs_zod = any(m in methods for m in ('POST', 'PUT', 'PATCH'))
    imports = []
    if with_auth:
        imports.append("import { auth } from '@/auth';")
    if needs_zod:
        imports.append("import { z } from 'zod';")
    schema = (
        "\n"
        "// Whitelist of writable fields. Never let callers set ownerId/role/etc.\n"
        "const ItemSchema = z.object({\n"
        "  name: z.string().min(1),\n"
        "  // Add more fields\n"
        "});\n"
    ) if needs_zod else ''

    fmt = dict(sig=sig, auth_check=auth_check, params_line=params_line,
               owner_filter=owner_filter, owner_data=owner_data,
               where=where, lookup=lookup)
    handlers = []
    for method in ROUTE_METHODS[kind]:  # stable order
        if method not in methods:
            continue
        if method == 'GET':
            key = 'route_get_item' if is_item else 'route_get_collection'
        elif method == 'POST':
            key = 'route_post_collection'
        elif method == 'DELETE':
            key = 'route_delete_item'
        else:
            key = 'route_update_item'
        handlers.append(TEMPLATES[key].format(method=method, **fmt))

    content = TEMPLATES['route_handler'].format(
        header=TEMPLATES['route_no_auth_warning'] if not with_auth else '',
        imports=''.join(f'{i}\n' for i in imports),
        schema=schema,
        handlers='\n'.join(handlers),
    )

    write_files([(path / 'route.ts', content)], args.force)
    if not with_auth:
        print("WARNING: --no-auth: generated handlers have NO authentication or "
              "ownership checks. Add them before handling private data or writes.",
              file=sys.stderr)


def generate_middleware(args):
    """Generate proxy.ts (Next.js 16) or legacy middleware.ts."""
    root = Path(args.path)

    # The file must sit next to the app directory: src/ for src/app projects,
    # otherwise the project root (a root file is silently ignored with src/app).
    uses_src = (root / 'src' / 'app').is_dir() and not (root / 'app').is_dir()
    base = root / 'src' if uses_src else root

    func = 'middleware' if args.legacy_middleware else 'proxy'
    other = 'proxy' if args.legacy_middleware else 'middleware'
    target = base / f'{func}.ts'

    conflicts = [base / f'{other}.{ext}' for ext in ('ts', 'js') if (base / f'{other}.{ext}').exists()]
    if conflicts:
        # Refused even with --force: --force only overwrites the target file,
        # and Next.js does not support a proxy and a middleware file side by side.
        for c in conflicts:
            print(f"Error: {c} already exists. Next.js does not support both a {func} "
                  f"and a {other} file; --force does not override this.", file=sys.stderr)
            print(f"  Remove {c} first, or rename it to {c.with_name(func + c.suffix)} "
                  f"and its exported function to `{func}` instead of generating a new file.",
                  file=sys.stderr)
        print("Nothing was written.", file=sys.stderr)
        sys.exit(1)

    content = TEMPLATES['proxy'].format(func=func)
    write_files([(target, content)], args.force)
    if uses_src:
        print("Note: project uses src/app, so the file was placed in src/")
    if args.legacy_middleware:
        print("Note: middleware.ts is deprecated in Next.js 16 - prefer proxy.ts")


def generate_component(args):
    """Generate a client component."""
    path = Path(args.path)
    name = args.name or to_pascal_case(path.name)
    require_identifier(name, '--name' if args.name else 'derived component name')
    title = args.title or name

    content = TEMPLATES['client_component'].format(
        name=name,
        title_jsx=jsx_text(title)
    )

    write_files([(path / f'{name}.tsx', content)], args.force)


def main():
    parser = argparse.ArgumentParser(
        description="Generate Next.js components with proper structure."
    )
    subparsers = parser.add_subparsers(dest='command', help='Component type to generate')

    # Shared options
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument('--force', '-f', action='store_true',
                        help='Overwrite existing files (default: refuse and exit 1)')

    # Page parser
    page_parser = subparsers.add_parser('page', parents=[common], help='Generate a page component')
    page_parser.add_argument('--path', '-p', required=True, help='Path to page directory')
    page_parser.add_argument('--name', '-n', help='Component name')
    page_parser.add_argument('--title', '-t', help='Page title')
    page_parser.add_argument('--description', '-d', help='Page description')
    page_parser.add_argument('--cached', action='store_true', help='Use cache directive')
    page_parser.add_argument('--with-loading', action='store_true', help='Include loading.tsx')
    page_parser.add_argument('--with-error', action='store_true', help='Include error.tsx')

    # Layout parser
    layout_parser = subparsers.add_parser('layout', parents=[common], help='Generate a layout component')
    layout_parser.add_argument('--path', '-p', required=True, help='Path to layout directory')
    layout_parser.add_argument('--name', '-n', help='Component name')
    layout_parser.add_argument('--title', '-t', help='Layout title')
    layout_parser.add_argument('--description', '-d', help='Layout description')

    # Action parser
    action_parser = subparsers.add_parser('action', parents=[common], help='Generate a Server Action')
    action_parser.add_argument('--path', '-p', required=True, help='Path to actions directory')
    action_parser.add_argument('--name', '-n', help='Action function name')
    action_parser.add_argument('--safe-action', action='store_true', help='Use next-safe-action pattern')

    # Route parser
    route_parser = subparsers.add_parser('route', parents=[common], help='Generate a Route Handler')
    route_parser.add_argument('--path', '-p', required=True, help='Path to route directory')
    route_parser.add_argument('--methods', '-m', default='GET', help='HTTP methods (comma-separated)')
    auth_group = route_parser.add_mutually_exclusive_group()
    auth_group.add_argument('--with-auth', action='store_true',
                            help='(Default; kept for compatibility) authenticate every handler')
    auth_group.add_argument('--no-auth', action='store_true',
                            help='Omit auth/ownership checks (public data only; emits a loud warning)')

    # Middleware parser
    middleware_parser = subparsers.add_parser('middleware', parents=[common], help='Generate proxy.ts (or middleware.ts)')
    middleware_parser.add_argument('--path', '-p', default='.', help='Path to project root')
    middleware_parser.add_argument('--legacy-middleware', action='store_true',
                                   help='Generate deprecated middleware.ts instead of proxy.ts')

    # Component parser
    component_parser = subparsers.add_parser('component', parents=[common], help='Generate a client component')
    component_parser.add_argument('--path', '-p', required=True, help='Path to component directory')
    component_parser.add_argument('--name', '-n', help='Component name')
    component_parser.add_argument('--title', '-t', help='Component title')

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return

    generators = {
        'page': generate_page,
        'layout': generate_layout,
        'action': generate_action,
        'route': generate_route,
        'middleware': generate_middleware,
        'component': generate_component,
    }

    generator = generators.get(args.command)
    if generator:
        generator(args)
    else:
        print(f"Unknown command: {args.command}")
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
