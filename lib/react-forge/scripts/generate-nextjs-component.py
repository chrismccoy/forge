#!/usr/bin/env python3
"""
Generate Next.js components with proper structure and patterns.

Run from the project root. Paths starting with `app/` are redirected to
`src/app/` when the project uses `src/app` and has no root `app/` directory.

Existing files are never overwritten: the script lists them, writes nothing,
and exits with status 1. Pass --force to overwrite. The middleware command
always refuses to create proxy.ts next to an existing middleware file (or the
reverse), even with --force.

Usage:
    python generate-nextjs-component.py page --path app/dashboard --name DashboardPage
    python generate-nextjs-component.py page --path app/blog/[slug] --with-loading --with-error
    python generate-nextjs-component.py page --path app/docs/[...slug]
    python generate-nextjs-component.py page --path app/products --cached
    python generate-nextjs-component.py layout --path app/dashboard
    python generate-nextjs-component.py action --path app/actions --name createPost
    python generate-nextjs-component.py route --path app/api/posts --methods GET,POST
    python generate-nextjs-component.py route --path app/api/posts/[id] --methods GET,PUT,DELETE
    python generate-nextjs-component.py route --path app/api/health --no-auth   # public; warns
    python generate-nextjs-component.py middleware              # proxy.ts (Next.js 16)
    python generate-nextjs-component.py middleware --legacy-middleware   # middleware.ts
    python generate-nextjs-component.py component --path components --name Counter
    python generate-nextjs-component.py page --path app/dashboard --force   # overwrite
"""

