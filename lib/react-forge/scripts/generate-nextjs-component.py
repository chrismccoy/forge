# Reserved words that cannot be used as an identifier (function/const name)
JS_RESERVED = {
    'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default',
    'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for',
    'function', 'if', 'import', 'in', 'instanceof', 'new', 'null', 'return', 'super',
    'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with',
    'yield', 'let', 'static', 'implements', 'interface', 'package', 'private',
    'protected', 'public', 'await', 'arguments', 'eval',
}
JS_IDENT_RE = re.compile(r'[A-Za-z_$][\w$]*', re.ASCII)


def require_identifier(name: str, what: str = '--name'):
    """Exit 1 unless name is a valid JavaScript identifier."""
    if not JS_IDENT_RE.fullmatch(name) or name in JS_RESERVED:
        print(f"Error: {what} {name!r} is not a valid JavaScript identifier "
              f"(letters, digits, _ or $; must not start with a digit or be a "
              f"reserved word). Pass a valid --name.", file=sys.stderr)
        sys.exit(1)


def js_string(s: str) -> str:
    """Return s as a single-quoted JS/TS string literal, properly escaped."""
    out = s.replace('\\', '\\\\').replace("'", "\\'")
    for ch, esc in (('\n', '\\n'), ('\r', '\\r'), ('\t', '\\t'),
                    ('\u2028', '\\u2028'), ('\u2029', '\\u2029')):
        out = out.replace(ch, esc)
    return f"'{out}'"


def jsx_text(s: str) -> str:
    """Return s for use as JSX text; wrap as {'...'} if it has JSX-special chars."""
    if re.search(r'[{}<>&\n\r]', s):
        return '{' + js_string(s) + '}'
    return s


def cache_tag_for(seg: str) -> str:
    """A cacheTag name safe inside both '...' and `...` literals."""
    return re.sub(r'[^\w-]', '_', seg.replace('-', '_')) or 'page'


def resolve_app_path(path: Path) -> Path:
    """
    Redirect `app/...` to `src/app/...` for projects that use `src/app`.

    Creating a root `app/` in a `src/app` project would make Next.js ignore
    `src/app` entirely, so never do that.
    """
    if path.parts and path.parts[0] == 'app' \
            and not Path('app').is_dir() and Path('src', 'app').is_dir():
        new_path = Path('src', *path.parts)
        print(f"Note: project uses src/app - writing to {new_path} instead of {path}", flush=True)
        return new_path
    return path


def write_files(files, force: bool):
    """
    Write (path, content) pairs. Refuses (exit 1, nothing written) if any
    target already exists, unless force is set.
    """
    existing = [f for f, _ in files if f.exists()]
    dirs = [f for f in existing if f.is_dir()]
    if dirs:
        for f in dirs:
            print(f"Error: target is a directory: {f}", file=sys.stderr)
        sys.exit(1)
    if existing and not force:
        for f in existing:
            print(f"Error: file already exists, refusing to overwrite: {f}", file=sys.stderr)
        print("Nothing was written. Re-run with --force to overwrite.", file=sys.stderr)
        sys.exit(1)

    for f, content in files:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding='utf-8')
        print(f"{'Overwrote' if f in existing else 'Created'}: {f}")


def to_pascal_case(s: str) -> str:
    """Convert string to PascalCase."""
    # Keep inner casing so createPost -> CreatePost (not Createpost)
    return ''.join(word[:1].upper() + word[1:] for word in s.replace('-', '_').split('_'))


def to_camel_case(s: str) -> str:
    """Convert string to camelCase."""
    pascal = to_pascal_case(s)
    return pascal[0].lower() + pascal[1:] if pascal else ''


def generate_page(args):
    """Generate a page component."""
    path = resolve_app_path(Path(args.path))
    seg = re.sub(r'[\[\]().@]', '', path.name) or 'Index'
    name = args.name or to_pascal_case(seg) + 'Page'
    require_identifier(name, '--name' if args.name else 'derived component name')
    title = args.title or seg.replace('-', ' ').title()
    description = args.description or f'{title} page'
    strings = dict(title_js=js_string(title), title_jsx=jsx_text(title),
                   description_js=js_string(description))

    # Determine if dynamic route: [id], [...slug] (catch-all), [[...slug]] (optional)
    is_dynamic = '[' in str(path)
    param = None
    if is_dynamic:
        dynamic = [m for part in path.parts
                   for m in [re.fullmatch(r'\[(\[)?(\.\.\.)?(\w+)\]?\]', part)] if m]
        match = dynamic[-1] if dynamic else None
        param = match.group(3) if match else 'id'
        optional = bool(match and match.group(1))
        catch_all = bool(match and match.group(2))
        param_key = f'{param}?' if optional else param
        param_type = 'string[]' if catch_all else 'string'
        if catch_all:
            param_display = f"{param}?.join('/') ?? ''" if optional else f"{param}.join('/')"
        else:
            param_display = param

    if args.cached and is_dynamic:
        # Await params outside the cache; pass the plain value into a cached fn
        statics = [p for p in path.parts if not p.startswith('[')]
        tag_seg = re.sub(r'[\[\]().@]', '', statics[-1]) if statics else seg
        template = TEMPLATES['page_cached_dynamic']
        content = template.format(
            name=name,
            param=param,
            param_key=param_key,
            param_type=param_type,
            param_arg_type=f'{param_type} | undefined' if optional else param_type,
            param_display=param_display,
            param_display_data=param_display.replace(param, f'data.{param}', 1),
            cache_tag=cache_tag_for(tag_seg),
            **strings
        )
    elif args.cached:
        template = TEMPLATES['page_cached']
        content = template.format(
            name=name,
            cache_tag=cache_tag_for(seg),
            **strings
        )
    elif is_dynamic:
        template = TEMPLATES['page_dynamic']
        content = template.format(
            name=name,
            param=param,
            param_key=param_key,
            param_type=param_type,
            param_display=param_display,
        )
    else:
        template = TEMPLATES['page_static']
        content = template.format(
            name=name,
            **strings
        )

    # Write files (all-or-nothing existence check)
    files = [(path / 'page.tsx', content)]
    if args.with_loading:
        files.append((path / 'loading.tsx', TEMPLATES['loading'].format()))
    if args.with_error:
        files.append((path / 'error.tsx', TEMPLATES['error'].format()))
    write_files(files, args.force)

    if args.cached:
        print("Note: 'use cache' requires `cacheComponents: true` in next.config.ts")
        if is_dynamic and not args.with_loading:
            print("Note: without generateStaticParams, a dynamic cached page needs a "
                  "<Suspense> boundary - add loading.tsx (--with-loading)")


def generate_layout(args):
    """Generate a layout component."""
    path = resolve_app_path(Path(args.path))
    seg = re.sub(r'[\[\]().@]', '', path.name) or 'Root'
    name = args.name or to_pascal_case(seg) + 'Layout'
    require_identifier(name, '--name' if args.name else 'derived component name')
    title = args.title or seg.replace('-', ' ').title()
    description = args.description or f'{title} section'

    content = TEMPLATES['layout'].format(
        name=name,
        title_js=js_string(title),
        title_template_js=js_string(f'%s | {title}'),
        description_js=js_string(description)
    )

    write_files([(path / 'layout.tsx', content)], args.force)


def generate_action(args):
    """Generate a Server Action."""
    path = resolve_app_path(Path(args.path))
    name = args.name or 'performAction'
    require_identifier(name)
    schema_name = to_pascal_case(name) + 'Schema'
    state_type = to_pascal_case(name) + 'State'

    if args.safe_action:
        content = TEMPLATES['action_safe'].format(
            name=name,
            schema_name=schema_name
        )
    else:
        content = TEMPLATES['action_basic'].format(
            name=name,
            schema_name=schema_name,
            state_type=state_type
        )

    # Determine filename: inside an `actions` directory -> one file per action
    # (segment match, so app/transactions does not count)
    if 'actions' in (part.lower() for part in path.parts):
        action_file = path / f'{to_camel_case(name)}.ts'
    else:
        action_file = path / 'actions.ts'

    # Never clobber an existing actions file (it may hold other actions)
    write_files([(action_file, content)], args.force)


